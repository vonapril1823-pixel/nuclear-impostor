#!/usr/bin/env node
/* Packs every image in ./faces into faces.js (as data URIs) so the game can use them as
 * avatar faces. Using data URIs keeps WebGL happy even when index.html is opened straight
 * from disk (file://), where browsers refuse to read pixels of normal image files.
 *
 *   npm run build:faces
 *
 * To add a face: drop a square-ish photo (about 128x128 px, JPG/PNG/WebP) into faces/
 * and run the command. The file name becomes the label: "face-03.jpg" -> "Face 3",
 * "kuya-ben.png" -> "Kuya Ben". Faces appear in the order of the file names.
 */
'use strict';
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const dir = path.join(root, 'faces');
const MIME = { '.jpg': 'image/jpeg', '.jpeg': 'image/jpeg', '.png': 'image/png', '.webp': 'image/webp' };

function label(file) {
  const base = path.basename(file, path.extname(file)).replace(/[-_]+/g, ' ').trim();
  const m = /^face\s*0*(\d+)$/i.exec(base);
  if (m) return 'Face ' + m[1];
  return base.replace(/\b\w/g, (c) => c.toUpperCase()).slice(0, 18);
}

const files = fs.existsSync(dir)
  ? fs.readdirSync(dir).filter((f) => MIME[path.extname(f).toLowerCase()]).sort((a, b) => a.localeCompare(b, undefined, { numeric: true }))
  : [];
const list = files.map((f) => {
  const buf = fs.readFileSync(path.join(dir, f));
  if (buf.length > 60 * 1024) console.warn('  note: ' + f + ' is ' + Math.round(buf.length / 1024) + ' KB. Shrink it to ~128 px to keep the game light.');
  return {
    id: path.basename(f, path.extname(f)).toLowerCase().replace(/[^a-z0-9]+/g, '-'),
    name: label(f),
    src: 'data:' + MIME[path.extname(f).toLowerCase()] + ';base64,' + buf.toString('base64'),
  };
});
const out =
  '/* Generated by scripts/build-faces.js from the images in faces/. Do not edit by hand. */\n' +
  'window.FACES=' + JSON.stringify(list) + ';\n';
fs.writeFileSync(path.join(root, 'faces.js'), out);
console.log('Wrote faces.js with ' + list.length + ' face(s): ' + list.map((f) => f.name).join(', '));
